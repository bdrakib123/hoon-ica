function mapChars(str, table) {
  return String(str).replace(/[A-Za-z0-9]/g, (ch) => table[ch] || ch);
}

const bold = (s) => mapChars(s, BOLD);
const italic = (s) => mapChars(s, ITALIC);
const monospace = (s) => mapChars(s, MONO);
const strike = (s) => String(s).replace(/[A-Za-z0-9]/g, (ch) => `${ch}\u0336`);

// Applies *bold*, _italic_, ~strike~ and ```mono``` wrappers.
function convert(text) {
  if (typeof text !== "string") return text;
  let out = text;
  out = out.replace(/\*\*\*(.+?)\*\*\*/gs, (_, m) => bold(italic(m)));
  out = out.replace(/\*\*(.+?)\*\*/gs, (_, m) => bold(m));
  out = out.replace(/__(.+?)__/gs, (_, m) => italic(m));
  out = out.replace(/\*(.+?)\*/gs, (_, m) => bold(m));
  out = out.replace(/(^|[^A-Za-z0-9])_([^_]+)_(?![A-Za-z0-9])/gs, (_, p, m) => p + italic(m));
  out = out.replace(/~~(.+?)~~/gs, (_, m) => strike(m));
  out = out.replace(/(^|[^~])~([^~]+)~(?![~])/gs, (_, p, m) => p + strike(m));
  out = out.replace(/```(.+?)```/gs, (_, m) => monospace(m));
  return out;
}

module.exports = { convert, bold, italic, strike, monospace };
